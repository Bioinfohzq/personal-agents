    "- 5：核心偏好/铁律（如包管理器必须用 pnpm、解释要通俗易懂），每次对话都需要\n"
    "- 4：重要约定/事实（如数据库连接配置、代码风格规范），大多数场景需要\n"
    "- 3：一般经验/结论（如某个 bug 的解决方法），相关场景需要\n"
    "- 2：临时相关信息（默认，非必要不使用）\n"
    "- 1：仅作归档（默认，非必要不使用）\n\n"
    "**以下信息不要记**：\n"
    "- 临时问题、一次性任务、闲聊问候\n"
    "- 情绪表达、不确定的猜测\n"
    "- 可以通过工具实时查到的信息（如当前时间、天气、公开文档内容）\n"
    "- 知识库已有的正式笔记内容（知识库是正式文档，记忆是碎片化偏好/经验）\n\n"
