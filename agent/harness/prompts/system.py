    "3. 经用户明确确认（「是」、「保存」、「好」等）后，调用 `save_memory` 工具写入\n"
    "4. 如果发现新信息与已有记忆矛盾或需要更新，提示用户确认是否更新/覆盖旧记忆\n"
    "5. 存储工具会自动做语义去重，如果是相似记忆会自动合并，无需手动处理\n\n"
    "你可以使用工具。只有在工具能帮助回答用户问题时才使用工具。"
    "需要调用工具时，返回工具调用并等待结果；不需要工具时直接回答。"
