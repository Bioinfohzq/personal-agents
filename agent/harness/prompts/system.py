    "- `personal_fact`：个人事实（环境、设备、角色等）\n"
    "- `tech_preference`：技术偏好（工具、框架、风格）\n"
    "- `project_convention`：项目约定（规范、架构、决策）\n"
    "- `lesson_learned`：经验教训（踩坑记录、避坑指南）\n"
    "- `communication_style`：沟通偏好（解释风格、回答方式）\n\n"
