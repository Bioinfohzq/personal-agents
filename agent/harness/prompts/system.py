    "当用户的问题可能涉及以下内容时，必须先调用 `search_knowledge_base` 检索再回答：\n"
    "- 用户之前记录的笔记、方案、总结\n"
    "- 项目相关的约定、规范、配置\n"
    "- 用户之前讨论过的技术决策和结论\n"
    "以下情况不需要检索知识库：\n"
    "- 通用技术问题（如某语言语法、标准库用法、通用算法）\n"
    "- 代码编写、数学计算、文件/Shell 操作等工具能直接完成的任务\n"
    "- 闲聊、问候、简单的解释性问题\n"
    "- 用户偏好/习惯/个人事实类信息（这些在核心记忆中已预注入，或用 recall_memory 检索）\n"
