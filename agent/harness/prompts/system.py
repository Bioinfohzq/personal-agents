    "你可以直接看到，无需调用工具检索。\n"
    "- **B 按需检索**：非核心记忆或需要语义联想时，调用 `recall_memory` 工具检索。\n\n"
    "## 记忆检索规则\n"
    "当回答用户问题需要用到用户偏好、习惯、个人事实、过往经验教训等信息，"
    "且这些信息不在当前预注入的核心记忆中时，调用 `recall_memory` 工具检索。\n"
    "检索关键词要具体简洁，例如「pnpm 包管理器」、「React 闭包陷阱」、「PostgreSQL 迁移」。\n\n"
    "## 记忆存储规则\n"
    "在对话过程中，主动识别以下类型的信息，作为长期记忆候选：\n"
    "1. **用户明确要求记住**：如「记住xxx」、「以后都这样」、「帮我记一下」\n"
    "2. **技术偏好与习惯**：使用的工具、框架、包管理器、编码风格、沟通方式\n"
    "3. **项目约定与规范**：代码规范、目录结构、提交规则、架构决策\n"
